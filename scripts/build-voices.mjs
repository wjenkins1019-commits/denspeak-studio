// Builds src/voices.ts from the full voice list the engine supports, keeping the
// curated names, genders and samples that were already in the file.
//
// vits-web declares every model id it can download (dist/types.d.ts). The app
// used to ship only the subset the original build happened to show, so this
// script merges both: curated metadata wins, everything else is derived from
// the id. Run it with `npm run gen:catalog`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const catalogPath = path.join(root, 'src', 'voices.ts');
const typesPath = path.join(
  root,
  'node_modules',
  '@diffusionstudio',
  'vits-web',
  'dist',
  'types.d.ts',
);

const ID_PATTERN = /'[a-z]{2,3}_[A-Z]{2,3}-[A-Za-z0-9_]+-(?:x_low|low|medium|high)'/g;

// The postinstall patch wires up a few en_US voices that the engine bundle does
// not declare; they belong in the catalog, so read them from the patch too.
const patchPath = path.join(root, 'scripts', 'patch-vits.mjs');
const declared = [
  ...(fs.readFileSync(typesPath, 'utf8').match(ID_PATTERN) ?? []),
  ...(fs.readFileSync(patchPath, 'utf8').match(ID_PATTERN) ?? []),
];

const ids = [...new Set(declared.map((match) => match.slice(1, -1)))].sort();

if (ids.length === 0) {
  console.error('No voice ids found in vits-web; refusing to write an empty catalog.');
  process.exit(1);
}

// Curated data already in the file (names, genders, preview lines).
const existing = new Map();
const rowPattern =
  /\{\s*id:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*language:\s*"([^"]+)",\s*quality:\s*"([^"]+)",(?:\s*gender:\s*"([^"]+)",)?\s*sample:\s*"([^"]*)"\s*\}/g;

const source = fs.readFileSync(catalogPath, 'utf8');
for (const match of source.matchAll(rowPattern)) {
  existing.set(match[1], {
    name: match[2],
    gender: match[5],
    sample: match[6],
  });
}

const titleCase = (text) =>
  text
    .replace(/_/g, ' ')
    .replace(/\btl\b/gi, 'tl')
    .replace(/^(.)|\s(.)/g, (character) => character.toUpperCase());

// Same speaker, several quality levels: keep the name readable but distinct.
const nameCounts = new Map();
for (const id of ids) {
  const [, speaker] = id.split('-');
  const curatedName = existing.get(id)?.name ?? titleCase(speaker);
  nameCounts.set(curatedName, (nameCounts.get(curatedName) ?? 0) + 1);
}

const usedNames = new Map();
const rows = ids.map((id) => {
  const [locale, speaker, quality] = id.split('-');
  const curated = existing.get(id);
  let name = curated?.name ?? titleCase(speaker);

  if (!curated && (nameCounts.get(name) ?? 0) > 1) {
    name = `${name} (${quality.replace('_', ' ')})`;
  }
  // Two quality tiers of the same speaker are allowed to share a curated name —
  // the label already ends with the quality. Only a real collision inside the
  // same language and quality gets disambiguated.
  const labelKey = `${locale}|${name}|${quality}`;
  if (usedNames.has(labelKey)) name = `${name} (${quality.replace('_', ' ')})`;
  usedNames.set(labelKey, id);

  const gender = curated?.gender ? ` gender: ${JSON.stringify(curated.gender)},` : '';
  const sample = curated?.sample ?? '';

  return `  { id: ${JSON.stringify(id)}, name: ${JSON.stringify(name)}, language: ${JSON.stringify(
    locale.replace('_', '-'),
  )}, quality: ${JSON.stringify(quality)},${gender} sample: ${JSON.stringify(sample)} },`;
});

const file = `// The voices the studio can speak with. Each id is a Piper/VITS model that
// vits-web downloads once and then keeps in the origin private file system.
//
// Generated by scripts/build-voices.mjs from the ids vits-web declares, merged
// with the curated names/samples that came from the original app. Run
// \`npm run gen:catalog\` after upgrading vits-web.

export type VoiceQuality = 'x_low' | 'low' | 'medium' | 'high';

export interface Voice {
  /** Piper model id — also the key vits-web uses. */
  id: string;
  name: string;
  /** BCP-47-ish tag, e.g. "en-US". */
  language: string;
  quality: VoiceQuality;
  gender?: 'female' | 'male' | 'neutral';
  /** A short line the voice can read aloud as a preview. */
  sample: string;
}

export const VOICES: Voice[] = [
${rows.join('\n')}
];

export const VOICES_BY_ID = new Map(VOICES.map((voice) => [voice.id, voice]));

const displayNames =
  typeof Intl !== 'undefined' && 'DisplayNames' in Intl
    ? new Intl.DisplayNames(['en'], { type: 'language' })
    : null;

/** "en-US" -> "English (US)". */
export function languageName(tag: string): string {
  const [language, region] = tag.split('-');
  const base = displayNames?.of(language) ?? language;
  return region ? \`\${base} (\${region})\` : base;
}

export function voiceLabel(voice: Voice): string {
  return \`\${voice.name} — \${languageName(voice.language)} (\${voice.quality.replace('_', ' ')})\`;
}
`;

fs.writeFileSync(catalogPath, file);
console.log(`Wrote ${ids.length} voices to src/voices.ts (${existing.size} curated).`);
